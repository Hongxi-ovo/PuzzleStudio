import assert from 'node:assert/strict';
import {cardAngle,isFaceDown,cardSurface} from '../web/card-display.mjs';
import {fieldMarkup} from '../web/field-layout.mjs';
assert.equal(cardAngle(1),0);
assert.equal(cardAngle(4),-90);
assert.equal(cardAngle(8),-90);
assert.equal(cardAngle(1,true),180);
assert.equal(cardAngle(4,true),90);
assert.equal(cardAngle(8,false,false),0);
assert.equal(cardAngle(8,true,false),180);
assert.equal(isFaceDown(1),false);
assert.equal(isFaceDown(4),false);
assert.equal(isFaceDown(8),true);
assert.equal(isFaceDown(2),true);
const surface=cardSurface(135598,'测试',8,-90,'board:test');
assert(surface.includes('card-back.jpg')&&surface.includes('is-facedown'));
assert(surface.includes('data-angle="-90"')&&surface.includes('/card-image/135598'));
assert(!fieldMarkup(5,()=>'<slot>',()=>'<pile>').includes('双方共用'));
console.log('Card display: angles, flip state, complete faces and EX labels passed.');
